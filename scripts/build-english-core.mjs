import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(root, "data/english/manifest.json");
const sourcePath = resolve(root, "data/english/english-core-5k.txt");
const outputPath = resolve(root, "src/data/english-core.generated.ts");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const bank = manifest.banks.find(
  (candidate) => candidate.id === "english_core",
);
if (!bank) throw new Error("English Core manifest entry is missing");
const words = (await readFile(sourcePath, "utf8"))
  .split(/\r?\n/)
  .filter(Boolean);

if (words.length !== bank.count) {
  throw new Error(
    `Expected ${bank.count} English Core words, found ${words.length}`,
  );
}
const allowedWord = new RegExp(bank.normalization.allowPattern);
const excludedTokens = new Set(bank.normalization.excludedTokens);
if (
  new Set(words).size !== words.length ||
  words.some((word) => !allowedWord.test(word) || excludedTokens.has(word))
) {
  throw new Error(
    "English Core source must contain unique lowercase ASCII words",
  );
}

const output = `// Generated by scripts/build-english-core.mjs. Do not edit manually.\n// Source: data/english/manifest.json (${bank.source.name} ${bank.source.version}, ${bank.source.license}).\n\nexport const englishCoreWords: string[] = [\n${words.map((word) => `  ${JSON.stringify(word)},`).join("\n")}\n];\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    throw new Error("English Core output is stale. Run npm run build:data.");
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
}
