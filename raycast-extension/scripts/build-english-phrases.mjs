import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = resolve(root, "data/english/manifest.json");
const sourcePath = resolve(root, "data/english/english-phrases-2000.txt");
const outputPath = resolve(root, "src/data/english-phrases.generated.ts");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const bank = manifest.banks.find(
  (candidate) => candidate.id === "english_phrases",
);
if (!bank) throw new Error("English Phrases manifest entry is missing");
const phrases = (await readFile(sourcePath, "utf8"))
  .split(/\r?\n/)
  .filter(Boolean);

if (phrases.length !== bank.count) {
  throw new Error(
    `Expected ${bank.count} English phrases, found ${phrases.length}`,
  );
}
if (
  new Set(phrases).size !== phrases.length ||
  phrases.some((phrase) => {
    const wordCount = phrase.trim().split(/\s+/).length;
    return (
      !/^[A-Z].*[.!?]["']?$/.test(phrase) ||
      /[^\x20-\x7E]/.test(phrase) ||
      wordCount < bank.normalization.minimumWords ||
      wordCount > bank.normalization.maximumWords
    );
  })
) {
  throw new Error(
    "English Phrases must be unique, printable, and sentence-like",
  );
}

const output = `// Generated by scripts/build-english-phrases.mjs. Do not edit manually.\n// Source: data/english/manifest.json (${bank.source.name} v${bank.source.version}, ${bank.source.license}).\n\nexport const englishPhrases: string[] = [\n${phrases.map((phrase) => `  ${JSON.stringify(phrase)},`).join("\n")}\n];\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== output) {
    throw new Error("English Phrases output is stale. Run npm run build:data.");
  }
} else {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output);
}
